
from __future__ import annotations
from typing import Dict, Any, Optional, Union, List, Mapping, Protocol, Iterator, Iterable, Tuple, TYPE_CHECKING

if TYPE_CHECKING:
    class PythonLogger(Protocol):
        """Logger with SLF4J-like interface (maps to io.axual.ksml.proxy.log.LoggerBridge.PythonLogger)"""

        def getName(self) -> str: ...

        # Level checks
        def isTraceEnabled(self) -> bool: ...
        def isDebugEnabled(self) -> bool: ...
        def isInfoEnabled(self) -> bool: ...
        def isWarnEnabled(self) -> bool: ...
        def isErrorEnabled(self) -> bool: ...

        # Trace logging
        def trace(self, s: str, *args: Any) -> None: ...

        # Debug logging
        def debug(self, s: str, *args: Any) -> None: ...

        # Info logging
        def info(self, s: str, *args: Any) -> None: ...

        # Warn logging
        def warn(self, s: str, *args: Any) -> None: ...

        # Error logging
        def error(self, s: str, *args: Any) -> None: ...

    class CounterBridge(Protocol):
        """KSML Counter metric"""

        def increment(self) -> None: ...
        def increment(self, delta: int) -> None: ...

    class MeterBridge(Protocol):
        """KSML Meter metric"""

        def mark(self) -> None: ...
        def mark(self, nrOfEvents: int) -> None: ...

    class TimerBridge(Protocol):
        """KSML Timer metric"""

        def updateSeconds(self, valueSeconds: int) -> None: ...
        def updateMillis(self, valueMilliseconds: int) -> None: ...
        def updateNanos(self, valueNanoseconds: int) -> None: ...

    class MetricsBridge(Protocol):
        """Metrics bridge for creating custom metrics (maps to io.axual.ksml.proxy.metric.MetricsBridge)"""

        def counter(self, name: str) -> CounterBridge: ...
        def counter(self, name: str, tags: Mapping[str, str]) -> CounterBridge: ...

        def meter(self, name: str) -> MeterBridge: ...
        def meter(self, name: str, tags: Mapping[str, str]) -> MeterBridge: ...

        def timer(self, name: str) -> TimerBridge: ...
        def timer(self, name: str, tags: Mapping[str, str]) -> TimerBridge: ...

    class StoreIterator(Iterator[Dict[str, Any]], Protocol):
        """Iterator of {"key", "value"} dicts. Closed when all entries are read or the function returns."""

        def hasNext(self) -> bool: ...
        def next(self) -> Optional[Dict[str, Any]]: ...
        def peekNextKey(self) -> Optional[Any]: ...
        def close(self) -> None: ...

    class StateStore(Protocol):
        """Base interface for state stores"""

        def name(self) -> str: ...
        def persistent(self) -> bool: ...
        def isOpen(self) -> bool: ...

    class KeyValueStore(StateStore, Protocol):
        """Key-Value store interface"""

        def get(self, key: Any) -> Optional[Any]: ...
        def put(self, key: Any, value: Any) -> None: ...
        def putIfAbsent(self, key: Any, value: Any) -> Optional[Any]: ...
        def delete(self, key: Any) -> Optional[Any]: ...
        def range(self, from_key: Any, to_key: Any) -> StoreIterator:
            """Entries from from_key to to_key, both included. None means no bound."""
            ...
        def reverseRange(self, from_key: Any, to_key: Any) -> StoreIterator: ...
        def all(self) -> StoreIterator: ...
        def reverseAll(self) -> StoreIterator: ...
        def prefixScan(self, prefix: str) -> StoreIterator:
            """Entries whose key starts with prefix. For stores with string keys.

            Raises TypeError if prefix is not a string.
            """
            ...
        def putAll(self, entries: Iterable[Union[Tuple[Any, Any], List[Any], Dict[str, Any]]]) -> None:
            """Writes (key, value) pairs or {"key", "value"} dicts. None deletes. A bad entry raises and writes nothing."""
            ...
        def approximateNumEntries(self) -> int: ...

    class SessionStore(StateStore, Protocol):
        """Session store interface"""

        def put(self, key: Any, value: Any) -> None: ...
        def remove(self, key: Any) -> None: ...
        def fetch(self, key: Any) -> StoreIterator: ...
        def fetchSession(self, key: Any, sessionStartTime: int, sessionEndTime: int) -> Any: ...
        def backwardFetch(self, key: Any) -> StoreIterator: ...
        def findSessions(self, key: Any, earliestSessionEndTime: int, latestSessionStartTime: int) -> StoreIterator: ...
        def backwardFindSessions(self, key: Any, earliestSessionEndTime: int, latestSessionStartTime: int) -> StoreIterator: ...

    class WindowStore(StateStore, Protocol):
        """Window store interface"""

        def put(self, key: Any, value: Any, windowStartTimestamp: int) -> None: ...
        def fetch(self, key: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetch(self, key: Any, timeFrom: Any, timeTo: Any) -> StoreIterator: ...
        def backwardFetch(self, key: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetchAll(self, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetchAll(self, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def all(self) -> StoreIterator: ...
        def backwardAll(self) -> StoreIterator: ...

    class TimestampedKeyValueStore(StateStore, Protocol):
        """Timestamped Key-Value store interface.

        Methods without WithTimestamp in their name return the same results as on a KeyValueStore. Writes without
        a timestamp use the timestamp of the record that is being processed. The *WithTimestamp methods also
        return the timestamp: getWithTimestamp gives {"value", "timestamp"}, the iterators give entries with
        "key", "value" and "timestamp".
        """

        def get(self, key: Any) -> Optional[Any]: ...
        def getWithTimestamp(self, key: Any) -> Optional[Dict[str, Any]]: ...
        def put(self, key: Any, value: Any) -> None:
            """Stores the value with the timestamp of the record that is being processed."""
            ...
        def put(self, key: Any, value: Any, timestamp: int) -> None: ...
        def putIfAbsent(self, key: Any, value: Any) -> Optional[Any]: ...
        def putIfAbsent(self, key: Any, value: Any, timestamp: int) -> Optional[Any]: ...
        def putAll(self, entries: Union[Iterable[Tuple[Any, Any]], Iterable[Dict[str, Any]]]) -> None:
            """Like KeyValueStore.putAll; a dict entry may have a "timestamp". Default timestamp: the record's."""
            ...
        def delete(self, key: Any) -> Optional[Any]: ...
        def range(self, from_key: Any, to_key: Any) -> StoreIterator:
            """Entries from from_key to to_key, both included. None means no bound."""
            ...
        def rangeWithTimestamp(self, from_key: Any, to_key: Any) -> StoreIterator: ...
        def reverseRange(self, from_key: Any, to_key: Any) -> StoreIterator: ...
        def reverseRangeWithTimestamp(self, from_key: Any, to_key: Any) -> StoreIterator: ...
        def all(self) -> StoreIterator: ...
        def allWithTimestamp(self) -> StoreIterator: ...
        def reverseAll(self) -> StoreIterator: ...
        def reverseAllWithTimestamp(self) -> StoreIterator: ...
        def prefixScan(self, prefix: str) -> StoreIterator:
            """Entries whose key starts with prefix. For stores with string keys.

            Raises TypeError if prefix is not a string.
            """
            ...
        def prefixScanWithTimestamp(self, prefix: str) -> StoreIterator: ...
        def approximateNumEntries(self) -> int: ...

    class TimestampedWindowStore(StateStore, Protocol):
        """Timestamped Window store interface. Python gets it for the store of a windowed aggregate.

        Methods without WithTimestamp in their name return the same results as on a WindowStore. A put without a
        timestamp uses the timestamp of the record that is being processed. The *WithTimestamp methods also return
        the timestamp: fetchWithTimestamp(key, time) gives {"value", "timestamp"}, the iterators give entries with
        "key", "value" and "timestamp".
        """

        def put(self, key: Any, value: Any, windowStartTimestamp: int) -> None:
            """Stores the value in the window, with the timestamp of the record that is being processed."""
            ...
        def put(self, key: Any, value: Any, windowStartTimestamp: int, timestamp: int) -> None: ...
        def fetch(self, key: Any, time: int) -> Optional[Any]: ...
        def fetch(self, key: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetch(self, keyFrom: Any, keyTo: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetchWithTimestamp(self, key: Any, time: int) -> Optional[Dict[str, Any]]: ...
        def fetchWithTimestamp(self, key: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetchWithTimestamp(self, keyFrom: Any, keyTo: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetch(self, key: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetch(self, keyFrom: Any, keyTo: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetchWithTimestamp(self, key: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetchWithTimestamp(self, keyFrom: Any, keyTo: Any, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetchAll(self, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def fetchAllWithTimestamp(self, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetchAll(self, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def backwardFetchAllWithTimestamp(self, timeFrom: int, timeTo: int) -> StoreIterator: ...
        def all(self) -> StoreIterator: ...
        def allWithTimestamp(self) -> StoreIterator: ...
        def backwardAll(self) -> StoreIterator: ...
        def backwardAllWithTimestamp(self) -> StoreIterator: ...

    class VersionedKeyValueStore(StateStore, Protocol):
        """Versioned Key-Value store interface"""

        def get(self, key: Any) -> Optional[Dict[str, Any]]: ...
        def get(self, key: Any, asOfTimestamp: int) -> Optional[Dict[str, Any]]: ...
        def put(self, key: Any, value: Any, timestamp: int) -> int: ...
        def delete(self, key: Any, timestamp: int) -> Optional[Dict[str, Any]]: ...

